logger = logging.getLogger("trustbook.overview")

OVERVIEW_KIND = "overview"
OVERVIEW_QUERY = "What are the main topics, key facts and conclusions of these sources?"
# Characters of a chunk's "[cN] Source: title (where)" line and spacing, for the estimate.
_HEADER_CHARS = 90

_sentences = TypeAdapter(list[SentenceOut])
_questions = TypeAdapter(list[str])


class OverviewError(Exception):
    """The overview cannot be (re)generated now. ``message`` is plain English."""

    def __init__(self, message: str) -> None:
        super().__init__(message)
        self.message = message


@dataclass(frozen=True)
class ChatState:
    """What the overview needs to know about the chat capability."""

    ready: bool
    remote: bool


@dataclass(frozen=True)
class OverviewResult:
    sentences: list[SentenceOut]
    questions: list[str]
    signature: str
    prompt_tokens: int


# --- pure parts ------------------------------------------------------------------------------


def spread_across_sources(
    ranked: Sequence[RetrievedChunk],
    *,
    max_chunks: int = CONTEXT_CHUNKS,
    max_tokens: int = CONTEXT_TOKENS,
) -> list[RetrievedChunk]:
    """Pick chunks round-robin over sources (best first in each), within the prompt budget.

    The overview should cover every source, not only the one the generic query likes best.
    """
    per_source: dict[str, list[RetrievedChunk]] = {}
    for chunk in ranked:
        per_source.setdefault(chunk.source_id, []).append(chunk)
    order: list[RetrievedChunk] = []
    depth = 0
    while len(order) < len(ranked):
        for chunks in per_source.values():
            if depth < len(chunks):
                order.append(chunks[depth])
        depth += 1
    return select_within_budget(
        order, lambda c: c.token_count, max_items=max_chunks, max_tokens=max_tokens
    )


def sources_signature(engine: Engine) -> str | None:
    """Fingerprint of the usable sources (id + snapshot time); None when there are none."""
    with Session(engine) as session:
        sources = usable_sources(session)
    if not sources:
        return None
    parts = sorted(f"{s.id}@{s.snapshot_at or s.created_at}" for s in sources)
    return hashlib.sha256("\n".join(parts).encode("utf-8")).hexdigest()[:32]


def estimate_prompt_tokens(engine: Engine) -> int | None:
    """Approximate tokens an overview sends: prompt text (chars / 4) plus the chunks in budget."""
    with Session(engine) as session:
        source_ids = [s.id for s in usable_sources(session)]
    count, tokens = total_tokens(engine, source_ids)
    if count == 0:
        return None
    chunks = min(count, CONTEXT_CHUNKS)
    fixed = len(OVERVIEW_SYSTEM) + len(CHUNKS_HEADING) + len(OVERVIEW_TASK) + 4
    return estimate_tokens(fixed + chunks * _HEADER_CHARS) + min(tokens, CONTEXT_TOKENS)


def generate_overview(
    engine: Engine,
    index: SpaceIndex,
    providers: ProviderRegistry,
    chat_adapter: ChatAdapterFactory,
    *,
    check_cancelled: Callable[[], None] = lambda: None,
) -> OverviewResult:
    """Retrieve over a generic "main topics" query plus each source's first chunk, then ask."""
    with Session(engine) as session:
        source_ids = [s.id for s in usable_sources(session)]
    if not source_ids:
        raise OverviewError("There are no ticked, ready sources to summarise.")
    signature = sources_signature(engine) or ""
    rows = candidates(engine, index, providers.embedder(), OVERVIEW_QUERY, source_ids)
    seen = {row.chunk_id for row in rows}
    rows += [row for row in first_chunks(engine, source_ids) if row.chunk_id not in seen]
    ranked = rerank(OVERVIEW_QUERY, rows, providers.reranker())
    chosen = spread_across_sources(ranked)
    if not chosen:
        raise OverviewError("The sources have no text to summarise yet.")
    check_cancelled()
    chunks = labelled(chosen)
    messages = overview_messages(chosen)
    try:
        parsed = generate_structured(
            chat_adapter(),
            messages,
            OVERVIEW_SCHEMA,
            lambda text: parse_overview(text, chunks.keys()),
        )
    except InvalidOutputError as exc:
        raise OverviewError("The chat model did not return a usable overview.") from exc
    if not parsed.answer.sentences:
        raise OverviewError("The chat model's overview did not cite your sources.")
    return OverviewResult(
        sentences=number_citations(parsed.answer.sentences, chunks),
        questions=parsed.questions,
        signature=signature,
        prompt_tokens=estimate_tokens(sum(len(m["content"]) for m in messages)),
    )


# --- storage ---------------------------------------------------------------------------------


class OverviewStore:
    """The single ``overview`` row of a space."""

    def __init__(self, engine: Engine) -> None:
        self._engine = engine

    def read(self) -> OverviewRow:
        with Session(self._engine) as session:
            row = session.get(OverviewRow, 1)
            if row is None:  # created by migration 002; recreate if someone deleted it
                row = OverviewRow(id=1, updated_at=utc_now_iso())
                session.add(row)
                session.commit()
                session.refresh(row)
            return row

    def update(self, **values: Any) -> OverviewRow:
        self.read()
        with Session(self._engine) as session:
            row = session.get(OverviewRow, 1)
            assert row is not None
            for key, value in values.items():
                setattr(row, key, value)
            row.updated_at = utc_now_iso()
            session.add(row)
            session.commit()
            session.refresh(row)
            return row


def _decode_sentences(raw: str) -> list[SentenceOut]:
    try:
        return _sentences.validate_json(raw or "[]")
    except ValidationError:
        return []


def _decode_questions(raw: str) -> list[str]:
    try:
        return _questions.validate_json(raw or "[]")
    except ValidationError:
        return []


# --- service ---------------------------------------------------------------------------------


class OverviewService:
    """Overview state, refresh jobs, the "source became ready" hook and the job handler."""

    def __init__(
        self,
        *,
        spaces: SpaceService,
        jobs: JobRepository,
        notify: Callable[[], None],
        indexes: IndexRegistry,
        providers: ProviderRegistry,
        chat_adapter: ChatAdapterFactory,
        chat_state: Callable[[], ChatState],
    ) -> None:
        self._spaces = spaces
        self._jobs = jobs
        self._notify = notify
        self._indexes = indexes
        self._providers = providers
        self._chat_adapter = chat_adapter
        self._chat_state = chat_state
        self._lock = threading.Lock()

    @staticmethod
    def _store(space: SpaceRecord) -> OverviewStore:
        return OverviewStore(get_engine(space.db_path))

    # --- queries ---------------------------------------------------------------------------

    def get(self, space: SpaceRecord) -> OverviewOut:
        engine = get_engine(space.db_path)
        row = OverviewStore(engine).read()
        status = self._status(row)
        sentences = _decode_sentences(row.sentences)
        signature = sources_signature(engine)
        stale = bool(row.generated_at) and signature != row.sources_signature
        tokens = estimate_prompt_tokens(engine)
        estimate = None
        if tokens is not None:
            estimate = OverviewEstimate(tokens=tokens, remote=self._chat_state().remote)
        return OverviewOut(
            enabled=row.enabled,
            status=status,
            sentences=sentences,
            questions=_decode_questions(row.questions),
            generated_at=row.generated_at,
            stale=stale,
            estimate=estimate,
        )

    def _status(self, row: OverviewRow) -> OverviewStatus:
        """Stored status, corrected when its job ended without writing a result."""
        if row.status != "pending":
            return _as_status(row.status)
        job_status = self._jobs.status(row.job_id) if row.job_id else None
        if job_status in UNFINISHED:
            return "pending"
        if job_status in ("failed", "done"):
            return "failed"
        return "ready" if row.generated_at else "none"  # cancelled or gone

    def _unfinished_job(self, row: OverviewRow) -> Job | None:
        if not row.job_id or self._jobs.status(row.job_id) not in UNFINISHED:
            return None
        return self._jobs.get(row.job_id)

    # --- commands --------------------------------------------------------------------------

    def set_enabled(self, space: SpaceRecord, enabled: bool) -> OverviewOut:
        store = self._store(space)
        store.update(enabled=enabled)
        if not enabled:
            job = self._unfinished_job(store.read())
            if job is not None and job.status != "running":
                self._jobs.cancel(job.id)
        return self.get(space)

    def refresh(self, space: SpaceRecord) -> Job:
        """Queue a (re)generation; an already waiting or running one is returned instead."""
        store = self._store(space)
        with self._lock:
            row = store.read()
            if not row.enabled:
                raise OverviewError("Turn the overview on first.")
            existing = self._unfinished_job(row)
            if existing is not None:
                return existing
            if not self._chat_state().ready:
                raise OverviewError("Set up the chat model in Settings first.")
            if sources_signature(get_engine(space.db_path)) is None:
                raise OverviewError("Add a source and wait until it is ready, or tick one.")
            return self._enqueue(space, store)

    def on_source_ready(self, space_id: str, source_id: str) -> None:
        """Hook for ingestion: write the first overview once a source is ready (if enabled).

        Only with a local chat model (DECISIONS D-029, SPEC §11): with a remote one the user first
        sees the token estimate and starts it with "Write overview" (refresh). Stale overviews are
        never refreshed automatically.
        """
        try:
            space = self._spaces.find(space_id)
            state = self._chat_state()
            if space is None or not state.ready or state.remote:
                return
            store = self._store(space)
            with self._lock:
                row = store.read()
                if not row.enabled or row.generated_at or self._unfinished_job(row) is not None:
                    return
                self._enqueue(space, store)
            logger.info("Queued the first overview of space %s (source %s)", space_id, source_id)
        except Exception:
            # Never break ingestion because the overview could not be queued.
            logger.exception("Could not queue the overview of space %s", space_id)

    def _enqueue(self, space: SpaceRecord, store: OverviewStore) -> Job:
        job = self._jobs.enqueue(OVERVIEW_KIND, "Write overview", space_id=space.id)
        store.update(status="pending", job_id=job.id, error=None)
        self._notify()
        return job

    # --- job handler -----------------------------------------------------------------------

    def handler(self, ctx: JobContext) -> None:
        """Generate the overview of ``ctx.space_id`` and store it."""
        if ctx.space_id is None:
            raise OverviewError("The overview job has no space.")
        space = self._spaces.get(ctx.space_id)
        engine = get_engine(space.db_path)
        store = OverviewStore(engine)
        try:
            result = generate_overview(
                engine,
                self._indexes.for_space(space.id),
                self._providers,
                self._chat_adapter,
                check_cancelled=ctx.check_cancelled,
            )
            ctx.check_cancelled()
        except Exception as exc:
            if store.read().job_id == ctx.job_id and not ctx.is_cancelled():
                message = getattr(exc, "message", None)
                store.update(status="failed", error=str(message or exc)[:500])
            raise
        if store.read().job_id != ctx.job_id:
            return  # a newer refresh took over
        store.update(
            status="ready",
            sentences=json.dumps([s.model_dump() for s in result.sentences], ensure_ascii=False),
            questions=json.dumps(result.questions, ensure_ascii=False),
            generated_at=utc_now_iso(),
            sources_signature=result.signature,
            error=None,
        )
        logger.info(
            "Wrote the overview of space %s (about %d tokens sent)", space.id, result.prompt_tokens
        )


def _as_status(value: str) -> OverviewStatus:
    if value == "ready":
        return "ready"
    if value == "failed":
        return "failed"
    if value == "pending":
        return "pending"
    return "none"
