"""The space overview (SPEC §9): a short grounded summary plus three suggested questions.

Generated by a queued job (kind ``overview``) when the first source of a space becomes ready and
the chat model is local, and otherwise on request (after the user has seen the token estimate).
It uses the same forced-citation format as answers (grounding layer 3).
"""

